import { describe, expect, it } from 'vitest'
import { axisUnitLabel, BINARY_INCREMENTS, columnFormat, formatInScale, formatParts, formatValue, headWithUnit, joinParts, scaleFor } from './units'

describe('value and unit are separate outputs (M7)', () => {
  it('formats the number and names the unit apart', () => {
    expect(formatParts(453.2, 'rps')).toEqual({ value: '453', unit: '/s' })
    expect(formatParts(1234, 'rps')).toEqual({ value: '1.23', unit: 'k/s' })
    expect(formatParts(0.0425, 'seconds')).toEqual({ value: '42.5', unit: 'ms' })
    expect(formatParts(1536, 'bytes')).toEqual({ value: '1.5', unit: 'KiB' })
    expect(formatParts(1536, 'bytes/s')).toEqual({ value: '1.5', unit: 'KiB/s' })
    expect(formatParts(0.0421, 'percentunit')).toEqual({ value: '4.21', unit: '%' })
    expect(formatParts(1234, 'none')).toEqual({ value: '1.23k', unit: '' })
    expect(formatParts(null, 'rps')).toEqual({ value: '–', unit: '' })
    expect(formatParts(NaN, 'bytes')).toEqual({ value: 'NaN', unit: '' })
  })
  it('CPU cores carry their unit', () => {
    expect(formatParts(1.42, 'cores')).toEqual({ value: '1.42', unit: 'cores' })
    expect(formatParts(0.357, 'cores')).toEqual({ value: '357', unit: 'millicores' })
    expect(formatValue(1.42, 'cores')).toBe('1.42 cores')
    expect(formatValue(0.357, 'cores')).toBe('357 millicores')
    expect(formatValue(0, 'cores')).toBe('0 cores')
  })
  it('joins a standalone value and its unit the way they are read', () => {
    expect(joinParts({ value: '453', unit: '/s' })).toBe('453/s')
    expect(joinParts({ value: '1.23', unit: 'k/s' })).toBe('1.23k/s')
    expect(joinParts({ value: '4.21', unit: '%' })).toBe('4.21%')
    expect(joinParts({ value: '42.5', unit: 'ms' })).toBe('42.5 ms')
    expect(joinParts({ value: '1.5', unit: 'KiB/s' })).toBe('1.5 KiB/s')
    expect(joinParts({ value: '12', unit: '' })).toBe('12')
    expect(formatValue(0.00042, 'rps')).toBe('420µ/s')
  })
})

describe('where the unit goes: once in the head, or on every value (M7)', () => {
  it('a column with one scale states the unit once and its cells are numbers', () => {
    const c = columnFormat([136, 117, 171, null], 'rps')
    expect(c.unit).toBe('/s')
    expect([136, 117, 171].map(c.cell)).toEqual(['136', '117', '171'])
    expect(c.cell(null)).toBe('–')
    expect(headWithUnit('Last', c.unit)).toBe('Last, /s')
  })
  it('one scale for the whole column, chosen from its largest value', () => {
    const c = columnFormat([0.357, 1.42, 0.5], 'cores')
    expect(c.unit).toBe('cores') // not "357m" beside "1.42"
    expect([0.357, 1.42, 0.5].map(c.cell)).toEqual(['0.357', '1.42', '0.5'])
    const m = columnFormat([0.357, 0.5], 'cores')
    expect(m.unit).toBe('millicores')
    expect(m.cell(0.357)).toBe('357')
    const b = columnFormat([900 * 1024 ** 2, 1.5 * 1024 ** 3], 'bytes')
    expect(b.unit).toBe('GiB')
    expect(b.cell(900 * 1024 ** 2)).toBe('0.879')
    const s = columnFormat([0.012, 0.25, 0.9], 'seconds')
    expect(s.unit).toBe('ms')
    expect(s.cell(0.25)).toBe('250')
    const p = columnFormat([0.01, 0.5], 'percentunit')
    expect(p.unit).toBe('%')
    expect(p.cell(0.5)).toBe('50')
  })
  it('a column that mixes scales keeps the unit on every value and has none in its head', () => {
    const c = columnFormat([0.002, 3 * 3600], 'seconds')
    expect(c.unit).toBeNull()
    expect(c.cell(0.002)).toBe('2 ms')
    expect(c.cell(3 * 3600)).toBe('3 h')
    expect(headWithUnit('Last', c.unit)).toBe('Last')
    const b = columnFormat([12, 4 * 1024 ** 3], 'bytes')
    expect(b.unit).toBeNull()
    expect(b.cell(12)).toBe('12 B')
  })
  it('plain numbers have no unit to state, and zeros and gaps do not make a column mixed', () => {
    const n = columnFormat([1, 1500], 'none')
    expect(n.unit).toBe('')
    expect(n.cell(1500)).toBe('1.5k')
    expect(headWithUnit('Value', n.unit)).toBe('Value')
    expect(columnFormat([0, null, 250], 'rps').unit).toBe('/s')
    expect(columnFormat([], 'bytes').unit).toBe('B')
    expect(columnFormat([null], 'seconds').unit).toBe('s')
  })
  it('an axis is always one scale', () => {
    const ticks = [0, 0.001, 50, 100]
    expect(columnFormat(ticks, 'seconds', 4).unit).toBeNull()
    expect(columnFormat(ticks, 'seconds', 4, false).unit).toBe('s')
  })
  it('the axis scale formats ticks as numbers, and the panel head names the unit once', () => {
    const scale = scaleFor('bytes', 900 * 1024 ** 2)
    expect(scale).toEqual({ factor: 1024 ** 2, symbol: 'MiB' })
    expect(formatInScale(768 * 1024 ** 2, 'bytes', scale, 4)).toBe('768')
    expect(axisUnitLabel('bytes', scale)).toBe('bytes, in MiB')
    expect(axisUnitLabel('rps', scaleFor('rps', 171))).toBe('per second (/s)')
    expect(axisUnitLabel('rps', scaleFor('rps', 17100))).toBe('per second, in k/s')
    expect(axisUnitLabel('cores', scaleFor('cores', 1.4))).toBe('CPU cores')
    expect(axisUnitLabel('cores', scaleFor('cores', 0.4))).toBe('CPU cores, in millicores')
    expect(axisUnitLabel('seconds', scaleFor('seconds', 0.2))).toBe('seconds, in ms')
    expect(axisUnitLabel('none', scaleFor('none', 5))).toBeUndefined()
  })
  it('byte axes tick on powers of two', () => {
    expect(BINARY_INCREMENTS.slice(0, 4)).toEqual([1, 2, 4, 8])
    expect(BINARY_INCREMENTS).toContain(128 * 1024 ** 2)
    expect(BINARY_INCREMENTS.every((v, i, a) => i === 0 || v === a[i - 1]! * 2)).toBe(true)
  })
})
