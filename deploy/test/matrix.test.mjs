// node --test deploy/test/: the CI matrix skips what a checkout lacks.
import assert from 'node:assert/strict'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { test } from 'node:test'
import { REPO_ROOT } from '../lib/common.mjs'
import { RUST, TS, matrix } from '../ci/matrix.mjs'

function fakeCheckout(dirs) {
  const root = mkdtempSync(join(tmpdir(), 'viz-matrix-'))
  for (const d of dirs) {
    mkdirSync(join(root, d), { recursive: true })
    writeFileSync(join(root, d, 'package.json'), '{}')
    writeFileSync(join(root, d, 'package-lock.json'), '{}')
  }
  return root
}

test('a checkout without app/ and design-system/ skips them; query excludes only its benchmark, whose fixtures are generated', () => {
  const root = fakeCheckout([...TS.map((c) => c.dir).filter((d) => d !== 'app' && d !== 'design-system'), 'bench'])
  for (const c of RUST) {
    mkdirSync(join(root, c), { recursive: true })
    writeFileSync(join(root, c, 'Cargo.toml'), '')
  }
  try {
    const m = matrix(root)
    const dirs = m.ts.map((t) => t.dir)
    assert.ok(!dirs.includes('app') && !dirs.includes('design-system'))
    assert.ok(dirs.includes('query') && dirs.includes('stack') && dirs.includes('deploy'))
    const query = m.ts.find((t) => t.dir === 'query')
    // The benchmark's fixtures are git-ignored and CI does not generate them; the tests' fixtures it does.
    assert.equal(query.exclude, 'test/signals.bench.ts')
    assert.match(m.notices.join('\n'), /query\/test\/signals.bench.ts: excluded because query\/test\/fixtures\/signals\/bench-small.json is not in this checkout/)
    assert.equal(query.install, 'edge')
    assert.equal(query.rust, true)
    assert.equal(query.prepare, 'tools/gen-signal-fixtures.sh')
    assert.equal(m.ts.find((t) => t.dir === 'stack').exclude, '')
    // Every component whose tests read files back with hyparquet installs bench/.
    for (const d of ['stack', 'flush', 'compact', 'engine/wasm']) assert.equal(m.ts.find((t) => t.dir === d).install, 'bench', d)
    for (const t of m.ts.filter((t) => t.dir !== 'query')) assert.deepEqual([t.rust, t.prepare], [false, ''], t.dir)
    assert.match(m.notices.join('\n'), /app: not in this checkout/)
    assert.doesNotMatch(m.notices.join('\n'), /query\/test\/http.test.ts/)
    assert.deepEqual(m.rust, RUST)
    // Without bench/, stack's end-to-end test (hyparquet from bench/node_modules) is excluded.
    rmSync(join(root, 'bench'), { recursive: true })
    assert.equal(matrix(root).ts.find((t) => t.dir === 'stack').exclude, 'test/e2e.test.ts')
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
})

test('with app/ and design-system/ present, and the benchmark fixtures, nothing is excluded; app needs design-system', () => {
  const root = fakeCheckout(TS.map((c) => c.dir))
  mkdirSync(join(root, 'app/src/api'), { recursive: true })
  writeFileSync(join(root, 'app/src/api/client.ts'), '')
  try {
    const m = matrix(root)
    assert.ok(m.ts.some((t) => t.dir === 'app'))
    assert.equal(m.ts.find((t) => t.dir === 'query').exclude, 'test/signals.bench.ts')
    // Once the benchmark's fixtures are there (generated by hand, as on a developer's machine), it is checked too.
    mkdirSync(join(root, 'query/test/fixtures/signals'), { recursive: true })
    writeFileSync(join(root, 'query/test/fixtures/signals/bench-small.json'), '{}')
    assert.equal(matrix(root).ts.find((t) => t.dir === 'query').exclude, '')
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
  const noDs = fakeCheckout(TS.map((c) => c.dir).filter((d) => d !== 'design-system'))
  try {
    assert.ok(!matrix(noDs).ts.some((t) => t.dir === 'app'))
  } finally {
    rmSync(noDs, { recursive: true, force: true })
  }
})

test('every optional exclusion still has its reason: the test file still imports what it needs', () => {
  for (const c of TS) {
    for (const o of c.optional ?? []) {
      assert.ok(o.imports, `${c.dir}/${o.file}: an optional exclusion must name the import that justifies it`)
      const text = readFileSync(join(REPO_ROOT, c.dir, o.file), 'utf8')
      assert.ok(text.includes(o.imports), `${c.dir}/${o.file} no longer contains "${o.imports}": drop the exclusion so the file runs in CI`)
    }
  }
})

test('every directory a component installs from is imported by one of its tests or prepare scripts', () => {
  // An install that nothing needs costs a job a minute; one that is missing fails the job (flush, compact,
  // engine/wasm and query each failed on pull request #9 for a directory that was not installed).
  const mentions = { flush: 'test/signals.test.ts', compact: 'test/signals.test.ts', 'engine/wasm': 'test/signal.test.ts', stack: 'test/e2e.test.ts' }
  for (const [dir, file] of Object.entries(mentions)) {
    assert.match(readFileSync(join(REPO_ROOT, dir, file), 'utf8'), /bench\/node_modules\/hyparquet/, `${dir}/${file}`)
    assert.deepEqual(TS.find((c) => c.dir === dir).install, ['bench'], dir)
  }
  const gen = readFileSync(join(REPO_ROOT, 'query/tools/gen-signal-fixtures.sh'), 'utf8')
  assert.match(gen, /edge\/scripts\/otel-corpus\.mjs/)
  assert.match(gen, /cargo build/)
  assert.match(readFileSync(join(REPO_ROOT, 'edge/scripts/otel-corpus.mjs'), 'utf8'), /from 'protobufjs'/)
})
