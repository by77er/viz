// Generates, from project/tokens.json and src/components.css (the generation itself is tools/css.mjs, shared with check.mjs):
//   project/components/bundle.css  component CSS with the type custom properties it needs (published with the reference)
//   dist/tokens.css                every token as a custom property, both themes
//   dist/viz.css                   fonts + tokens + components in one file, for the app
//   dist/viz-chart.js              the reference chart from the Chart preview, for the fixture, compositions and screen designs
//   dist/viz-press.js              the press state for every pointer (src/press.js): a finger's press painted from pointerdown
//   dist/fonts/                    the self-hosted font files
// tokens.json is the single source of every value. Nothing generated is edited by hand.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs'
import { basename } from 'node:path'
import { buildCss } from './css.mjs'
const root = new URL('..', import.meta.url).pathname
const { t, tokensCss, bundle, viz } = buildCss(root)
writeFileSync(root + 'project/components/bundle.css', bundle)
mkdirSync(root + 'dist/fonts', { recursive: true })
for (const f of t.type.fonts) copyFileSync(root + 'project/' + f.file, root + 'dist/fonts/' + basename(f.file))
writeFileSync(root + 'dist/tokens.css', tokensCss)
writeFileSync(root + 'dist/viz.css', viz)
// The reference chart, taken from the Chart preview (its one source), for the fixture dashboard, compositions and screen designs.
const chart = readFileSync(root + 'project/components/Chart/preview.html', 'utf8').match(/<script>([\s\S]*?)<\/script>/)
if (chart) writeFileSync(root + 'dist/viz-chart.js', '/* viz reference chart: generated by tools/build.mjs from project/components/Chart/preview.html. Do not edit. */\n' + chart[1])
writeFileSync(root + 'dist/viz-press.js', '/* viz press state: generated by tools/build.mjs from src/press.js. Do not edit. */\n' + readFileSync(root + 'src/press.js', 'utf8'))
console.log('wrote project/components/bundle.css, dist/tokens.css, dist/viz.css, dist/viz-chart.js, dist/viz-press.js, dist/fonts/')
