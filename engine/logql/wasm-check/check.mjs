// node check.mjs <module.wasm>: imports, exports, instantiation with {}, one query.
import { readFileSync } from 'node:fs';
const bytes = readFileSync(process.argv[2]);
const mod = new WebAssembly.Module(bytes);
const imports = WebAssembly.Module.imports(mod);
console.log('imports:', imports.length, JSON.stringify(imports));
console.log('exports:', WebAssembly.Module.exports(mod).map((e) => e.name).join(', '));
let t0 = performance.now();
const N = 200;
let inst;
for (let i = 0; i < N; i++) inst = new WebAssembly.Instance(mod, {});
console.log('instantiate with {}: mean', ((performance.now() - t0) / N).toFixed(3), 'ms over', N);
const { memory, viz_logql_alloc, viz_logql_free, viz_logql_query } = inst.exports;
const S = 1000000000n;
const rows = [];
for (let i = 0; i < 1000; i++) rows.push(`app=web,env=prod\t${(1700000000n * S + BigInt(i) * S).toString()}\tlevel=${i % 3 ? 'info' : 'error'} status=${200 + (i % 5)} latency=${i % 97}ms`);
const req = `sum by (level) (count_over_time({app="web"} | logfmt | __error__="" [1m]))\n${1700000000n * S} ${1700001000n * S} ${60n * S} 100 0\n` + rows.join('\n');
const enc = new TextEncoder().encode(req);
const p = viz_logql_alloc(enc.length);
new Uint8Array(memory.buffer, p, enc.length).set(enc);
t0 = performance.now();
const r = viz_logql_query(p, enc.length);
const ms = performance.now() - t0;
const rp = Number(r >> 32n), rl = Number(r & 0xffffffffn);
const out = new TextDecoder().decode(new Uint8Array(memory.buffer, rp, rl));
viz_logql_free(p, enc.length);
viz_logql_free(rp, rl);
const data = JSON.parse(out);
console.log('query: resultType', data.resultType, 'series', data.result.length, 'first', JSON.stringify(data.result[0].values.slice(0, 2)), `${ms.toFixed(1)} ms`);
const bad = new TextEncoder().encode('sum(\n0 1 1 100 0\n');
const p2 = viz_logql_alloc(bad.length);
new Uint8Array(memory.buffer, p2, bad.length).set(bad);
const r2 = viz_logql_query(p2, bad.length);
console.log('bad query:', new TextDecoder().decode(new Uint8Array(memory.buffer, Number(r2 >> 32n), Number(r2 & 0xffffffffn))));
console.log('memory:', memory.buffer.byteLength, 'bytes');
